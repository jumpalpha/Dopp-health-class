// tools/build_classwork_bank.js — builds the Unit Classwork test bank.
//   node tools/build_classwork_bank.js
// Sources: quick_checks_data.js (QC_BANK, recall), smart_questions.js (SMART_Q with a chapter, recall),
//          classwork_questions.js (CW_REASON, reasoning / higher order).
// Writes:
//   classwork_bank.js            the page's copy: [id, chapter, kind, question, correct, wrong, wrong, wrong, why]
//   supabase/classwork_bank.sql  the database copy: id, chapter, kind and a hash of the correct answer
//                                (the database grades the Chapter and Unit Tests against the hash)
// Ids are a hash of the question text, so adding or reordering source rows never re-keys old questions.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
global.window = {};
['quick_checks_data.js', 'smart_questions.js', 'classwork_questions.js'].forEach(f => require(path.join(root, f)));
const md5 = s => crypto.createHash('md5').update(s, 'utf8').digest('hex');
const norm = s => String(s).trim().toLowerCase();

const rows = [], seen = new Set();
function add(ch, kind, q, right, w, why) {
  const id = md5(ch + '|' + norm(q)).slice(0, 10);
  if (seen.has(id) || !right || w.length < 3) return;
  seen.add(id);
  rows.push([id, ch, kind, q, right, w[0], w[1], w[2], why || '']);
}
for (let c = 1; c <= 28; c++) {
  (window.QC_BANK[c] || []).forEach(r => add(c, 'recall', r[1], r[2], r.slice(3, 6), r[6]));
  (window.SMART_Q || []).filter(r => r[2] === c).forEach(r => add(c, 'recall', r[3], r[4], r.slice(5, 8), r[8]));
  (window.CW_REASON[c] || []).forEach(r => add(c, 'reason', r[0], r[1], r.slice(2, 5), r[5]));
}

fs.writeFileSync(path.join(root, 'classwork_bank.js'),
  '// Generated by tools/build_classwork_bank.js. Do not edit by hand.\n' +
  '// [id, chapter, kind, question, correct, wrong, wrong, wrong, why]  (the page shuffles the answers)\n' +
  'window.CW_BANK = ' + JSON.stringify(rows) + ';\n');

const keyRows = rows.map(r => [r[0], r[1], r[2], md5(norm(r[4])).slice(0, 12)]);
fs.writeFileSync(path.join(root, 'supabase', 'classwork_bank.sql'),
  '-- Generated by tools/build_classwork_bank.js. Do not edit by hand. Safe to re-run.\n' +
  '-- Run AFTER supabase/classwork_v2.sql. Answer hashes for the Chapter and Unit Tests.\n' +
  "insert into public.cw_bank (id, chapter, kind, h) select r->>0, (r->>1)::int, r->>2, r->>3 from jsonb_array_elements('" +
  JSON.stringify(keyRows).replace(/'/g, "''") + "'::jsonb) r\n" +
  'on conflict (id) do update set chapter = excluded.chapter, kind = excluded.kind, h = excluded.h;\n');

const by = {}; rows.forEach(r => { const k = r[1]; by[k] = by[k] || { recall: 0, reason: 0 }; by[k][r[2]]++; });
