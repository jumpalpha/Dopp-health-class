// Regenerates pet_vocab.js from the vocab data in vocab_engine.html.
// Run from the repo folder: node tools/build_pet_vocab.js
const fs = require('fs');
const s = fs.readFileSync('vocab_engine.html', 'utf8');
const i = s.indexOf('const ALL_CHAPTERS');
let d = 0, a = s.indexOf('{', i), b = -1;
for (let k = a; k < s.length; k++) { if (s[k] === '{') d++; else if (s[k] === '}') { d--; if (!d) { b = k; break; } } }
const all = eval('(' + s.slice(a, b + 1) + ')');
const out = {};
for (const ch in all) out[ch] = { title: all[ch].title, terms: all[ch].terms.map(x => [x.t, x.d]) };
fs.writeFileSync('pet_vocab.js', '// Generated by tools/build_pet_vocab.js from vocab_engine.html. Do not edit by hand.\nwindow.PET_VOCAB = ' + JSON.stringify(out) + ';\n');
console.log('chapters', Object.keys(out).length, 'terms', Object.values(out).reduce((n, c) => n + c.terms.length, 0));
